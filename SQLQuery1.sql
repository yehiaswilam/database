/*
1. DELETE vs TRUNCATE

DELETE:
- Removes rows from a table.
- Can use a WHERE condition.
- Is logged row by row.
- DELETE can be used when specific rows need to be removed.
- The table structure remains.

TRUNCATE:
- Removes all rows from a table.
- Does not support a WHERE clause.
- Uses fewer log resources than DELETE in normal cases.
- Resets an IDENTITY counter in SQL Server.
- The table structure remains.

Example:
DELETE FROM Employees WHERE Id = 1;
TRUNCATE TABLE Employees;
*/

/*
2. TRANSACTION LOG BACKUP

A Transaction Log Backup is a backup of the database transaction log.
It records database changes so the transaction log can be backed up
and, with an appropriate recovery model, can support point-in-time
recovery.

Example:
BACKUP LOG CompanyDB
TO DISK = 'C:\Backup\CompanyDB_Log.trn';
*/

