3. WHAT IS A DATABASE JOB?

A database job is a scheduled task that automatically performs
database-related operations at a specified time or on a specified
schedule.

In SQL Server, jobs are commonly created and managed using SQL Server
Agent. Examples include backups, maintenance, data cleanup, and
scheduled stored procedure execution.
*/
