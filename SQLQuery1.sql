CREATE TABLE Employees
(
    Id INT PRIMARY KEY,
    FirstName VARCHAR(50),
    LastName VARCHAR(50),
    Salary DECIMAL(10,2)
);
GO

-- 1. GetAllEmployees
CREATE PROCEDURE GetAllEmployees
AS
BEGIN
    SELECT *
    FROM Employees;
END;
GO

-- 2. GetHighSalaryEmployees
CREATE PROCEDURE GetHighSalaryEmployees
    @MinSalary DECIMAL(10,2)
AS
BEGIN
    SELECT *
    FROM Employees
    WHERE Salary > @MinSalary;
END;
GO

-- 3. AddEmployee
CREATE PROCEDURE AddEmployee
    @FirstName VARCHAR(50),
    @LastName VARCHAR(50),
    @Salary DECIMAL(10,2)
AS
BEGIN
    INSERT INTO Employees (Id, FirstName, LastName, Salary)
    VALUES
    (
        ISNULL((SELECT MAX(Id) + 1 FROM Employees), 1),
        @FirstName,
        @LastName,
        @Salary
    );
END;
GO

-- =========================================================
-- PART 2: EMPLOYEE LOG + AFTER INSERT TRIGGER
-- =========================================================

CREATE TABLE EmployeeLog
(
    Id INT IDENTITY(1,1) PRIMARY KEY,
    EmployeeId INT,
    Action VARCHAR(50),
    ActionDate DATETIME
);
GO

CREATE TRIGGER trg_AfterInsertEmployee
ON Employees
AFTER INSERT
AS
BEGIN
    INSERT INTO EmployeeLog (EmployeeId, Action, ActionDate)
    SELECT
        Id,
        'INSERT',
        GETDATE()
    FROM inserted;
END;
GO

